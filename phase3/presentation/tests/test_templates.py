class TestBaseTemplate:
    def test_cannot_instantiate_abc(self) -> None:
        with pytest.raises(TypeError):
            BaseTemplate()

    def test_default_methods(self) -> None:
        class MinimalTemplate(BaseTemplate):
            @property
            def name(self) -> str:
                return "minimal"

            @property
            def description(self) -> str:
                return "Minimal"

            @property
            def report_type(self) -> str:
                return "minimal"

        t = MinimalTemplate()
        assert t.sections() == []
        assert t.chart_types() == []
        assert t.title({}) == "Minimal Report"
        assert t.subtitle({}) == "Generated by IdeaFormator Pipeline"

        t.configure(config)
        assert t._config is config


