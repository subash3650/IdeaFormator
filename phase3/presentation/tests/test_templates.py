class TestSectionsOrdering:
    def test_all_templates_sections_ordered(self) -> None:
        for name in available_templates():
            t = create_template(name)
            sections = t.sections()
            for i in range(len(sections) - 1):
                assert sections[i].order <= sections[i + 1].order, (
                    f"Template '{name}' sections not ordered: "
                    f"{sections[i].title}({sections[i].order}) > "
                    f"{sections[i+1].title}({sections[i+1].order})"
                )

    def test_no_duplicate_orders(self) -> None:
        for name in available_templates():
            t = create_template(name)
            orders = [s.order for s in t.sections()]
            assert len(orders) == len(set(orders)), (
                f"Template '{name}' has duplicate section orders: {orders}"
            )

    def test_no_duplicate_section_types(self) -> None:
        for name in available_templates():
            t = create_template(name)
            types = [s.section_type for s in t.sections()]
            assert len(types) == len(set(types)), (
                f"Template '{name}' has duplicate section types: {types}"
            )
