class TestTemplateInheritance:
    def test_executive_inherits_business_sections(self) -> None:
        executive = ExecutiveTemplate()
        business = BusinessTemplate()
        exec_types = {s.section_type for s in executive.sections()}
        bus_types = {s.section_type for s in business.sections()}
        assert bus_types.issubset(exec_types)

    def test_investor_inherits_business_sections(self) -> None:
        investor = InvestorTemplate()
        business = BusinessTemplate()
        inv_types = {s.section_type for s in investor.sections()}
        bus_types = {s.section_type for s in business.sections()}
        assert bus_types.issubset(inv_types)

    def test_founder_inherits_business_sections(self) -> None:
        founder = FounderTemplate()
        business = BusinessTemplate()
        fnd_types = {s.section_type for s in founder.sections()}
        bus_types = {s.section_type for s in business.sections()}
        assert bus_types.issubset(fnd_types)

    def test_market_inherits_business_sections(self) -> None:
        market = MarketTemplate()
        business = BusinessTemplate()
        mkt_types = {s.section_type for s in market.sections()}
        bus_types = {s.section_type for s in business.sections()}
        assert bus_types.issubset(mkt_types)

    def test_technology_not_inheriting_business(self) -> None:
        assert not isinstance(TechnologyTemplate(), BusinessTemplate)
        assert not issubclass(TechnologyTemplate, BusinessTemplate)

    def test_configure_all_templates(self, config: PresentationConfig) -> None:
        for name in available_templates():
            t = create_template(name)
            t.configure(config)
            assert t._config is config


